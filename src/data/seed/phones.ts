export const links: AffiliateLink[] = [];

export const phones: Phone[] = seed.map(({ demoPrices, ...p }) => {
  const query = `${p.brand} ${p.model}`;
  const offers: PriceOffer[] = demoPrices.map((d, i) => {
    const linkId = `lnk-${p.slug}-${d.storeId.replace("store-", "")}`;
    links.push({
      id: linkId,
      label: `${query} · ${d.storeId.replace("store-", "")}`,
      storeId: d.storeId,
      targetUrl: storeSearch[d.storeId]?.(query) ?? "",
      active: true,
      applyAffiliate: true,
      createdAt: seedDate,
      updatedAt: seedDate,
    });
    return {
      id: `off-${p.slug}-${i}`,
      storeId: d.storeId,
      price: d.price,
      currency: "EUR",
      linkId,
      checkedAt: seedDate,
      source: "demo",
      variant: d.variant,
    };
  });
  return {
    ...p,
    offers,
    updatedAt: seedDate,
    isDemo: true,
    specsVerified: false,
    image: {
      src: `/demo/phones/${p.slug}.webp`,
      alt: `Ilustración de ${query}`,
      illustrative: true,
      width: 800,
      height: 1000,
    },
  };
});
